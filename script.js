// Evaluation Metrics Calculator
function evaluateModel(model, X_test, y_test) {
    let correct = 0;
    const confusionMatrix = [
        [0, 0, 0],
        [0, 0, 0],
        [0, 0, 0]
    ];
    
    // Accumulators for report calculation
    const support = [0, 0, 0];
    const truePositives = [0, 0, 0];
    const predPositives = [0, 0, 0];
    
    for (let i = 0; i < X_test.length; i++) {
        const x = X_test[i];
        const yTrue = y_test[i];
        const res = model.predictSingle(x);
        const yPred = res.predictedClass;
        
        confusionMatrix[yTrue][yPred]++;
        support[yTrue]++;
        predPositives[yPred]++;
        
        if (yTrue === yPred) {
            correct++;
            truePositives[yTrue]++;
        }
    }
    
    const accuracy = correct / X_test.length;
    
    const precision = [0, 0, 0];
    const recall = [0, 0, 0];
    const f1 = [0, 0, 0];
    
    for (let c = 0; c < 3; c++) {
        precision[c] = predPositives[c] > 0 ? truePositives[c] / predPositives[c] : 0;
        recall[c] = support[c] > 0 ? truePositives[c] / support[c] : 0;
        f1[c] = (precision[c] + recall[c]) > 0 ? 2 * (precision[c] * recall[c]) / (precision[c] + recall[c]) : 0;
    }
    
    return {
        accuracy,
        confusionMatrix,
        precision,
        recall,
        f1
    };
}

