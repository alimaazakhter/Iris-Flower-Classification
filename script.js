// 1. Logistic Regression (Multiclass Softmax Gradient Descent)
class LogisticRegression {
    constructor(learningRate = 0.1, maxIter = 500) {
        this.lr = learningRate;
        this.maxIter = maxIter;
    }
    
    fit(X, y) {
        const nSamples = X.length;
        const nFeatures = X[0].length;
        const nClasses = 3;
        
        // Scale data for stable gradient descent
        this.scaler = new StandardScaler();
        this.scaler.fit(X);
        const X_scaled = this.scaler.transform(X);
        
        // Initialize weights (3 classes x 4 features) and biases (3 classes)
        this.W = Array.from({ length: nClasses }, () => new Array(nFeatures).fill(0));
        this.b = new Array(nClasses).fill(0);
        
        // Training Loop
        for (let iter = 0; iter < this.maxIter; iter++) {
            // Gradient accumulations
            const dW = Array.from({ length: nClasses }, () => new Array(nFeatures).fill(0));
            const db = new Array(nClasses).fill(0);
            
            for (let i = 0; i < nSamples; i++) {
                const x_i = X_scaled[i];
                const y_i = y[i];
                
                // Calculate Softmax Probabilities
                const scores = new Array(nClasses);
                let maxScore = -Infinity;
                for (let c = 0; c < nClasses; c++) {
                    let dot = 0;
                    for (let f = 0; f < nFeatures; f++) {
                        dot += this.W[c][f] * x_i[f];
                    }
                    scores[c] = dot + this.b[c];
                    if (scores[c] > maxScore) maxScore = scores[c];
                }
                
                // Softmax stable trick
                let sumExp = 0;
                const expScores = new Array(nClasses);
                for (let c = 0; c < nClasses; c++) {
                    expScores[c] = Math.exp(scores[c] - maxScore);
                    sumExp += expScores[c];
                }
                
                const probs = expScores.map(val => val / sumExp);
                
                // Gradients: loss w.r.t logits
                for (let c = 0; c < nClasses; c++) {
                    const indicator = (y_i === c) ? 1.0 : 0.0;
                    const error = probs[c] - indicator;
                    
                    db[c] += error;
                    for (let f = 0; f < nFeatures; f++) {
                        dW[c][f] += error * x_i[f];
                    }
                }
            }
            
            // Weight and bias update
            for (let c = 0; c < nClasses; c++) {
                this.b[c] -= (this.lr / nSamples) * db[c];
                for (let f = 0; f < nFeatures; f++) {
                    this.W[c][f] -= (this.lr / nSamples) * dW[c][f];
                }
            }
        }
    }
    
    predictSingle(x) {
        const x_scaled = this.scaler.transformSingle(x);
        const nClasses = 3;
        const scores = new Array(nClasses);
        
        let maxScore = -Infinity;
        for (let c = 0; c < nClasses; c++) {
            let dot = 0;
            for (let f = 0; f < x.length; f++) {
                dot += this.W[c][f] * x_scaled[f];
            }
            scores[c] = dot + this.b[c];
            if (scores[c] > maxScore) maxScore = scores[c];
        }
        
        let sumExp = 0;
        const expScores = new Array(nClasses);
        for (let c = 0; c < nClasses; c++) {
            expScores[c] = Math.exp(scores[c] - maxScore);
            sumExp += expScores[c];
        }
        
        const probs = expScores.map(val => val / sumExp);
        const maxProb = Math.max(...probs);
        const predictedClass = probs.indexOf(maxProb);
        
        return {
            predictedClass,
            probabilities: probs
        };
    }
}

// 2. K-Nearest Neighbors (KNN)
class KNNClassifier {
    constructor(k = 3, metric = 'euclidean') {
        this.k = k;
        this.metric = metric;
    }
    
    fit(X, y) {
        this.X_train = X;
        this.y_train = y;
    }
    
    distance(pt1, pt2) {
        if (this.metric === 'manhattan') {
            return pt1.reduce((sum, val, idx) => sum + Math.abs(val - pt2[idx]), 0);
        }
        const sumSq = pt1.reduce((sum, val, idx) => sum + Math.pow(val - pt2[idx], 2), 0);
        return Math.sqrt(sumSq);
    }
    
    predictSingle(xQuery) {
        const dists = this.X_train.map((xTrain, idx) => ({
            dist: this.distance(xQuery, xTrain),
            label: this.y_train[idx]
        }));
        
        dists.sort((a, b) => a.dist - b.dist);
        const kNearest = dists.slice(0, this.k);
        
        const votes = [0, 0, 0];
        kNearest.forEach(n => votes[n.label]++);
        
        const sum = votes.reduce((a, b) => a + b, 0);
        const probs = votes.map(v => v / sum);
        const predictedClass = votes.indexOf(Math.max(...votes));
        
        return {
            predictedClass,
            probabilities: probs
        };
    }
}

// 3. Decision Tree (CART Implementation)
class DecisionTree {
    constructor(maxDepth = 3) {
        this.maxDepth = maxDepth;
        this.root = null;
    }
    
    // Gini Impurity Calculator
    gini(labels) {
        const n = labels.length;
        if (n === 0) return 0;
        const counts = [0, 0, 0];
        labels.forEach(lbl => counts[lbl]++);
        const sumSqProbs = counts.reduce((sum, count) => sum + Math.pow(count / n, 2), 0);
        return 1.0 - sumSqProbs;
    }
    
    // Split Helper
    split(X, y, featureIdx, threshold) {
        const leftX = [], leftY = [];
        const rightX = [], rightY = [];
        
        for (let i = 0; i < X.length; i++) {
            if (X[i][featureIdx] <= threshold) {
                leftX.push(X[i]);
                leftY.push(y[i]);
            } else {
                rightX.push(X[i]);
                rightY.push(y[i]);
            }
        }
        return { leftX, leftY, rightX, rightY };
    }
    
    // Recursive Tree Builder
    buildTree(X, y, depth) {
        const nSamples = X.length;
        const nLabels = new Set(y).size;
        
        // Calculate class frequencies
        const counts = [0, 0, 0];
        y.forEach(lbl => counts[lbl]++);
        const probs = counts.map(c => nSamples > 0 ? c / nSamples : 0);
        const majorityClass = counts.indexOf(Math.max(...counts));
        
        // Base cases
        if (depth >= this.maxDepth || nLabels <= 1 || nSamples < 2) {
            return { isLeaf: true, majorityClass, probabilities: probs };
        }
        
        let bestGini = Infinity;
        let bestSplit = null;
        const nFeatures = X[0].length;
        
        // Find best split
        for (let f = 0; f < nFeatures; f++) {
            // Sort unique thresholds
            const values = X.map(row => row[f]);
            const uniqueVals = [...new Set(values)].sort((a, b) => a - b);
            
            for (let i = 0; i < uniqueVals.length - 1; i++) {
                const threshold = (uniqueVals[i] + uniqueVals[i+1]) / 2;
                const { leftY, rightY } = this.split(X, y, f, threshold);
                
                if (leftY.length === 0 || rightY.length === 0) continue;
                
                // Weighted Gini
                const wGini = (leftY.length / nSamples) * this.gini(leftY) + 
                             (rightY.length / nSamples) * this.gini(rightY);
                             
                if (wGini < bestGini) {
                    bestGini = wGini;
                    bestSplit = { featureIdx: f, threshold, leftY, rightY };
                }
            }
        }
        
        // If no split improves Gini
        if (!bestSplit) {
            return { isLeaf: true, majorityClass, probabilities: probs };
        }
        
        const { leftX, leftY, rightX, rightY } = this.split(X, y, bestSplit.featureIdx, bestSplit.threshold);
        
        return {
            isLeaf: false,
            featureIdx: bestSplit.featureIdx,
            threshold: bestSplit.threshold,
            leftChild: this.buildTree(leftX, leftY, depth + 1),
            rightChild: this.buildTree(rightX, rightY, depth + 1),
            probabilities: probs
        };
    }
    
    fit(X, y) {
        this.root = this.buildTree(X, y, 0);
    }
    
    predictSingle(x) {
        let node = this.root;
        while (!node.isLeaf) {
            if (x[node.featureIdx] <= node.threshold) {
                node = node.leftChild;
            } else {
                node = node.rightChild;
            }
        }
        return {
            predictedClass: node.majorityClass,
            probabilities: node.probabilities
        };
    }
}

