function setupSandboxTraining() {
    const btn = document.getElementById("btn-train");
    
    // Hyperparameter radios
    const radios = document.getElementsByName("train-model");
    radios.forEach(radio => {
        radio.addEventListener("change", (e) => {
            // Update active parameter block
            document.querySelectorAll(".param-block").forEach(b => b.classList.remove("active"));
            document.getElementById(`params-${e.target.value}`).classList.add("active");
            
            // Update labels
            document.querySelectorAll(".radio-card").forEach(c => c.classList.remove("active"));
            e.target.closest(".radio-card").classList.add("active");
        });
    });
    
    // Connect range output listeners
    const sliderListeners = [
        { id: "split-ratio", valId: "split-ratio-val", fn: (v) => `${v}/${100-v}` },
        { id: "lr", valId: "lr-val", fn: (v) => v },
        { id: "epochs", valId: "epochs-val", fn: (v) => v },
        { id: "knn-k", valId: "knn-k-val", fn: (v) => v },
        { id: "tree-depth", valId: "tree-depth-val", fn: (v) => v }
    ];
    
    sliderListeners.forEach(cfg => {
        const slider = document.getElementById(cfg.id);
        const valEl = document.getElementById(cfg.valId);
        slider.addEventListener("input", (e) => {
            valEl.innerText = cfg.fn(e.target.value);
        });
    });
    
    // Train button callback
    btn.addEventListener("click", () => {
        // Run training state animation on button
        const oldContent = btn.innerHTML;
        btn.disabled = true;
        btn.innerHTML = `<span class="spinner"></span> <span>Training Model...</span>`;
        
        setTimeout(() => {
            const modelType = document.querySelector('input[name="train-model"]:checked').value;
            const splitVal = parseFloat(document.getElementById("split-ratio").value) / 100;
            
            // Split fresh data
            testSplitData = trainTestSplit(IRIS_DATA, splitVal);
            document.getElementById("metric-split-info").innerText = `On test split (${Math.round(splitVal*100)}/${Math.round((1-splitVal)*100)})`;
            
            let trainedModel = null;
            
            if (modelType === 'logistic') {
                const lr = parseFloat(document.getElementById("lr").value);
                const epochs = parseInt(document.getElementById("epochs").value);
                trainedLogistic = new LogisticRegression(lr, epochs);
                trainedLogistic.fit(testSplitData.X_train, testSplitData.y_train);
                trainedModel = trainedLogistic;
            } else if (modelType === 'knn') {
                const k = parseInt(document.getElementById("knn-k").value);
                const metric = document.getElementById("knn-metric").value;
                trainedKNN = new KNNClassifier(k, metric);
                trainedKNN.fit(testSplitData.X_train, testSplitData.y_train);
                trainedModel = trainedKNN;
            } else if (modelType === 'tree') {
                const depth = parseInt(document.getElementById("tree-depth").value);
                trainedTree = new DecisionTree(depth);
                trainedTree.fit(testSplitData.X_train, testSplitData.y_train);
                trainedModel = trainedTree;
            }
            
            // Re-evaluate
            const evalMetrics = evaluateModel(trainedModel, testSplitData.X_test, testSplitData.y_test);
            updateEvaluationUI(evalMetrics);
            
            // Synchronize predictors
            setActiveModel(document.getElementById("active-model-select").value);
            performLivePrediction();
            
            // Reset button state
            btn.disabled = false;
            btn.innerHTML = `<i data-lucide="check" class="btn-icon"></i> <span>Trained Successfully!</span>`;
            lucide.createIcons();
            
            setTimeout(() => {
                btn.innerHTML = oldContent;
                lucide.createIcons();
            }, 1500);
            
        }, 600); // simulated slight lag for animation effect
    });
}

