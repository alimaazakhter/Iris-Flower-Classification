    const speciesName = INVERSE_SPECIES_MAP[predClass];
    document.getElementById("predicted-species-name").innerText = DISPLAY_NAMES[speciesName];
    
    // Update progress bars
    document.getElementById("prob-setosa-pct").innerText = (probs[0] * 100).toFixed(0) + "%";
    document.getElementById("prob-setosa-bar").style.width = (probs[0] * 100) + "%";
    
